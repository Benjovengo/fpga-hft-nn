# =============================================================================
# Raw-data directory creation
# =============================================================================

def create_directories():
    """Create the directory used to store downloaded market data."""

    # Create data/raw/ if it does not already exist.
    #
    # parents=True:
    #     Also creates missing parent directories.
    #
    # exist_ok=True:
    #     Does not generate an exception when the directory already exists.
    RAW_DATA_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


# =============================================================================
# Period conversion
# =============================================================================

def parse_period_days(period):
    """Convert a day-based period string into an integer number of days."""

    # The chunked downloader currently expects the total acquisition period
    # to be expressed as:
    #
    #     <number>d
    #
    # Examples:
    #
    #     "8d"  -> 8 days
    #     "30d" -> 30 days
    #     "60d" -> 60 days
    #
    # Restricting the format here keeps the download-window calculation
    # explicit and prevents ambiguous conversions from units such as months
    # or years.
    if not period.endswith("d"):
        raise ValueError(
            "Chunked 1-minute downloads currently require "
            "DATA_PERIOD to use the '<number>d' format"
        )

    # Remove the trailing "d" and convert the remaining characters to an
    # integer.
    #
    # For example:
    #
    #     period = "30d"
    #
    # becomes:
    #
    #     period[:-1] = "30"
    #
    # and finally:
    #
    #     30
    return int(
        period[:-1]
    )


# =============================================================================
# Market-data acquisition
# =============================================================================

def download_data():
    """Download historical market data in provider-compatible chunks."""

    # Display the configured instrument and interval so that the acquisition
    # configuration is visible in the console output.
    print(
        f"Downloading {TICKER} "
        f"{DATA_INTERVAL} market data..."
    )

    # Convert the configured total period into a number of calendar days.
    #
    # For example:
    #
    #     DATA_PERIOD = "30d"
    #
    # produces:
    #
    #     number_days = 30
    number_days = parse_period_days(
        DATA_PERIOD
    )

    # Use the current UTC time as the end of the requested dataset.
    #
    # An explicit timezone-aware datetime is used to avoid ambiguity between
    # the local workstation timezone and the timestamps expected by the
    # market-data provider.
    end_time = datetime.now(
        timezone.utc
    )

    # Apply a safety margin before calculating the beginning of the complete
    # requested acquisition window. Yahoo checks the start timestamp against
    # its own current time, so a request starting exactly 30 days ago can be
    # rejected a few seconds later as being outside the allowed history.
    effective_days = max(
        1,
        number_days - DATA_HISTORY_MARGIN_DAYS,
    )

    # Calculate the beginning of the complete requested acquisition window.
    #
    # For a 30-day configuration:
    #
    #     start_time = now - 30 days
    #
    # The resulting interval is:
    #
    #     start_time ------------------------------ end_time
    #                         30 days
    start_time = (
        end_time
        -
        timedelta(
            days=effective_days
        )
    )

    # Store each successfully downloaded dataframe here.
    #
    # The individual chunks will be concatenated after all requests have
    # completed.
    chunks = []

    # The first request begins at the start of the complete acquisition
    # window.
    chunk_start = start_time

    # Yahoo restricts the amount of 1-minute data that can be retrieved by a
    # single request.
    #
    # Instead of requesting the complete period:
    #
    #     <--------------------- 30 days --------------------->
    #
    #                     one request
    #
    # divide the acquisition into smaller requests:
    #
    #     <-- 7d --><-- 7d --><-- 7d --><-- 7d --><-- 2d -->
    #
    # The chunks are later concatenated into one chronological dataframe.
    while chunk_start < end_time:

        # Calculate the end of the current request.
        #
        # Normally:
        #
        #     chunk_end = chunk_start + DATA_CHUNK_DAYS
        #
        # However, the final chunk may contain fewer days.
        #
        # For example, a 30-day acquisition using 7-day chunks produces:
        #
        #     chunk 1 = 7 days
        #     chunk 2 = 7 days
        #     chunk 3 = 7 days
        #     chunk 4 = 7 days
        #     chunk 5 = 2 days
        #
        # min() prevents the final request from extending beyond end_time.
        chunk_end = min(
            chunk_start
            +
            timedelta(
                days=DATA_CHUNK_DAYS
            ),
            end_time,
        )

        # Print each requested interval.
        #
        # This is useful for debugging provider limitations and confirming
        # that the configured period is being divided correctly.
        print(
            "Downloading chunk: "
            f"{chunk_start.isoformat()} "
            "-> "
            f"{chunk_end.isoformat()}"
        )

        # Download the current chunk.
        #
        # start and end are used instead of period because the script must
        # explicitly control the size of each individual request.
        #
        # interval=DATA_INTERVAL:
        #     Requests the configured sampling interval.
        #     The initial project uses 1-minute bars.
        #
        # auto_adjust=True:
        #     Requests automatically adjusted OHLC values where supported by
        #     the provider.
        #
        # progress=False:
        #     Disables the yfinance progress indicator so that the project's
        #     own chunk status messages remain clear.
        dataframe = yf.download(
            TICKER,
            start=chunk_start,
            end=chunk_end,
            interval=DATA_INTERVAL,
            auto_adjust=True,
            progress=False,
        )

        # A particular chunk can be empty because of weekends, holidays,
        # market closures, provider availability, or other reasons.
        #
        # Do not fail the complete acquisition because one chunk contains no
        # samples.
        #
        # Instead, append only valid chunks and verify after the loop that at
        # least one chunk was successfully retrieved.
        if not dataframe.empty:
            chunks.append(
                dataframe
            )

        # Continue the next request exactly where the current request ended.
        #
        # For example:
        #
        #     request 1: day 0 -> day 7
        #     request 2: day 7 -> day 14
        #     request 3: day 14 -> day 21
        #
        # This ensures continuous coverage of the requested period.
        chunk_start = chunk_end

    # Verify that at least one request returned usable market data.
    #
    # If every request failed or returned an empty dataframe, subsequent
    # processing stages cannot generate features or train the neural network.
    if not chunks:
        raise RuntimeError(
            "No market data downloaded"
        )

    # Combine all successfully downloaded chunks into one dataframe.
    #
    # Conceptually:
    #
    #     chunk 0 ─┐
    #     chunk 1 ─┤
    #     chunk 2 ─┼──> pd.concat() ──> complete dataset
    #     chunk 3 ─┤
    #     chunk 4 ─┘
    dataframe = pd.concat(
        chunks
    )

    # Remove duplicate timestamps.
    #
    # Adjacent provider requests may occasionally return overlapping samples
    # around their boundaries.
    #
    # The timestamp is the dataframe index, so duplicated index entries
    # represent duplicated market-data samples.
    #
    # keep="first" preserves the first occurrence and removes subsequent
    # copies.
    dataframe = dataframe[
        ~dataframe.index.duplicated(
            keep="first"
        )
    ]

    # Restore strict chronological ordering after concatenation.
    #
    # Downstream feature extraction and neural-network training depend on
    # temporal ordering, so this step must occur before the dataset is saved.
    dataframe = dataframe.sort_index()

    # Report the total number of samples assembled from all chunks.
    print(
        f"Downloaded {len(dataframe)} total rows"
    )

    return dataframe


# =============================================================================
# Dataframe normalization
# =============================================================================

def normalize_columns(dataframe):
    """Normalize the downloaded dataframe for subsequent processing."""

    # yfinance may return MultiIndex columns even when only one ticker is
    # requested.
    #
    # For example:
    #
    #     Price                Close      High       Low ...
    #     Ticker                AAPL      AAPL      AAPL ...
    #
    # The current project processes one instrument at a time, so the ticker
    # level is unnecessary.
    #
    # Keep only the first column level:
    #
    #     Close
    #     High
    #     Low
    #     Open
    #     Volume
    if dataframe.columns.nlevels > 1:
        dataframe.columns = (
            dataframe.columns
            .get_level_values(0)
        )

    # Convert all column names to lowercase.
    #
    # For example:
    #
    #     Open   -> open
    #     High   -> high
    #     Low    -> low
    #     Close  -> close
    #     Volume -> volume
    #
    # This provides a stable naming convention for python/features.py.
    dataframe.columns = [
        str(column).lower()
        for column in dataframe.columns
    ]

    # Give the datetime index an explicit name.
    #
    # When exported to CSV, the first column will therefore be:
    #
    #     timestamp
    #
    # instead of an unnamed dataframe index.
    dataframe.index.name = "timestamp"

    return dataframe


# =============================================================================
# Raw-data storage
# =============================================================================

def save_data(dataframe):
    """Save normalized market data as a CSV file."""

    # Store the timestamp index together with the OHLCV values.
    #
    # The resulting file has the general structure:
    #
    # timestamp,close,high,low,open,volume
    # 2026-...,123.45,123.60,123.30,123.40,100000
    # ...
    #
    # This is the raw input dataset for python/features.py.
    #
    # The generated CSV is excluded from Git because it can be reproduced by
    # running this script again.
    dataframe.to_csv(
        RAW_DATA_FILE,
        index=True,
    )

    # Report the number of stored samples.
    print(
        f"Saved {len(dataframe)} rows to:"
    )

    # Report the complete output path.
    print(
        RAW_DATA_FILE
    )


# =============================================================================
# Main data-acquisition flow
# =============================================================================

def main():
    """Execute the complete raw market-data acquisition flow."""

    # The complete acquisition pipeline is:
    #
    # Market-data provider
    #         |
    #         v
    # download_data()
    #         |
    #         +--> chunk 0
    #         +--> chunk 1
    #         +--> chunk 2
    #         +--> ...
    #         |
    #         v
    # concatenate chunks
    #         |
    #         v
    # remove duplicate timestamps
    #         |
    #         v
    # chronological dataframe
    #         |
    #         v
    # normalize_columns()
    #         |
    #         v
    # normalized OHLCV dataframe
    #         |
    #         v
    # save_data()
    #         |
    #         v
    # data/raw/aapl_1m.csv
    #         |
    #         v
    # python/features.py

    # Ensure that the raw-data destination exists before attempting to save
    # the downloaded dataset.
    create_directories()

    # Download the complete configured period using provider-compatible
    # chunks.
    dataframe = download_data()

    # Normalize the dataframe structure and column names so that downstream
    # scripts do not depend on the original provider-specific format.
    dataframe = normalize_columns(
        dataframe
    )

    # Store the normalized raw dataset for the next processing stage.
    save_data(
        dataframe
    )


# =============================================================================
# Script entry point
# =============================================================================

# Execute main() when this file is run as a Python module:
#
#     python -m python.download_data
#
# Importing functions from this module does not automatically start a market
# data download.
if __name__ == "__main__":
    main()
    