# =============================================================================
# Floating-point parameter loading
# =============================================================================

def load_parameters():
    """Load the floating-point parameters generated during training."""

    # python/train.py saves the Dense-layer parameters using np.savez().
    #
    # The resulting NPZ file contains:
    #
    #     hidden_weights
    #     hidden_bias
    #     output_weights
    #     output_bias
    #
    # For the current network:
    #
    #     hidden_weights.shape = (8, 8)
    #     hidden_bias.shape    = (8,)
    #     output_weights.shape = (8, 1)
    #     output_bias.shape    = (1,)
    #
    # The NPZ file allows quantization to be performed independently from
    # training.
    #
    # Therefore, changing the fixed-point format does not require the neural
    # network to be retrained.
    parameters = np.load(
        FLOAT_PARAMETER_FILE
    )

    return parameters


# =============================================================================
# CSV row generation
# =============================================================================

def create_parameter_row(
    parameter_type,
    layer,
    row,
    column,
    value,
):
    """Create one hardware-facing parameter record."""

    # Each quantized parameter is represented by one CSV row.
    #
    # The CSV schema is:
    #
    #     type
    #     layer
    #     row
    #     column
    #     value
    #     width
    #     fraction_bits
    #
    # Example:
    #
    #     weight,hidden,0,3,-127,16,12
    #
    # This means:
    #
    #     parameter type = weight
    #     layer          = hidden
    #     row            = 0
    #     column         = 3
    #     integer value  = -127
    #     storage width  = 16 bits
    #     fractional bits = 12
    #
    # The actual real-number approximation is:
    #
    #                       -127
    #     real_value = ----------------
    #                       2^12
    #
    #                = -127 / 4096
    #
    # The CSV therefore stores the integer representation rather than a
    # decimal floating-point value.
    return {
        "type": parameter_type,
        "layer": layer,
        "row": row,
        "column": column,
        "value": int(value),
        "width": FIXED_WIDTH,
        "fraction_bits": FRACTION_BITS,
    }


# =============================================================================
# Hidden-layer weight export
# =============================================================================

def export_hidden_weights(
    rows,
    hidden_weights,
):
    """Quantize and append hidden-layer weights to the CSV records."""

    # Keras stores Dense-layer weights using:
    #
    #     weights[input][neuron]
    #
    # Therefore, with eight inputs and eight hidden neurons:
    #
    #                    neuron
    #
    #               0   1   2       7
    #             +---+---+---+---+---+
    # input 0 ---> |   |   |   |...|   |
    #             +---+---+---+---+---+
    # input 1 ---> |   |   |   |...|   |
    #             +---+---+---+---+---+
    #     .        |   |   |   |   |   |
    #     .        |   |   |   |   |   |
    # input 7 ---> |   |   |   |...|   |
    #             +---+---+---+---+---+
    #
    # The original array is therefore indexed as:
    #
    #     hidden_weights[input][neuron]
    #
    # For the VHDL implementation, it is more convenient to organize the
    # weights by neuron:
    #
    #     weight[neuron][input]
    #
    # because each hardware neuron consumes all of its input weights.
    #
    # Transpose the matrix so the software export matches this hardware
    # organization.
    hardware_weights = hidden_weights.T

    # Quantize all hidden-layer weights.
    #
    # For the current Q format:
    #
    #     floating-point weight
    #              |
    #              v
    #        multiply by 4096
    #              |
    #              v
    #            round
    #              |
    #              v
    #          saturate
    #              |
    #              v
    #       signed integer
    quantized_weights = quantize_array(
        hardware_weights
    )

    # Iterate over every hidden neuron.
    #
    # After the transpose:
    #
    #     neuron_index
    #
    # identifies the hardware neuron.
    for neuron_index in range(
        quantized_weights.shape[0]
    ):

        # Iterate over every input connected to the current neuron.
        for input_index in range(
            quantized_weights.shape[1]
        ):

            # Append one CSV record for the connection:
            #
            #     input[input_index]
            #
            #             |
            #             X weight
            #             |
            #             v
            #
            #     hidden[neuron_index]
            rows.append(
                create_parameter_row(
                    parameter_type="weight",
                    layer="hidden",
                    row=neuron_index,
                    column=input_index,
                    value=quantized_weights[
                        neuron_index,
                        input_index,
                    ],
                )
            )


# =============================================================================
# Hidden-layer bias export
# =============================================================================

def export_hidden_bias(
    rows,
    hidden_bias,
):
    """Quantize and append hidden-layer biases to the CSV records."""

    # There is one bias for each hidden neuron.
    #
    # With:
    #
    #     HIDDEN_SIZE = 8
    #
    # the bias vector contains:
    #
    #     b[0]
    #     b[1]
    #     ...
    #     b[7]
    #
    # Each hidden neuron computes:
    #
    #              7
    #              ---
    #              \
    #     z[j] =    >   x[i] * W[j][i] + b[j]
    #              /
    #              ---
    #              i=0
    quantized_bias = quantize_array(
        hidden_bias
    )

    # Store one record for each hidden-neuron bias.
    for neuron_index in range(
        quantized_bias.shape[0]
    ):
        rows.append(
            create_parameter_row(
                parameter_type="bias",
                layer="hidden",
                row=neuron_index,

                # A bias is associated with a neuron rather than a particular
                # input column.
                #
                # Column 0 is therefore used as a conventional placeholder in
                # the common CSV schema.
                column=0,

                value=quantized_bias[
                    neuron_index
                ],
            )
        )


# =============================================================================
# Output-layer weight export
# =============================================================================

def export_output_weights(
    rows,
    output_weights,
):
    """Quantize and append output-layer weights to the CSV records."""

    # Keras stores the output Dense-layer weights as:
    #
    #     output_weights[hidden_neuron][output_neuron]
    #
    # For the current architecture:
    #
    #     HIDDEN_SIZE = 8
    #     OUTPUT_SIZE = 1
    #
    # therefore:
    #
    #     output_weights.shape = (8, 1)
    #
    # The hardware-oriented organization is:
    #
    #     weight[output_neuron][hidden_neuron]
    #
    # Transpose the Keras matrix to obtain this organization.
    hardware_weights = output_weights.T

    # After the transpose:
    #
    #     hardware_weights.shape = (1, 8)
    #
    # for the current network.
    quantized_weights = quantize_array(
        hardware_weights
    )

    # Iterate over every output neuron.
    #
    # The current architecture contains only one output neuron, but keeping
    # both dimensions makes the export format extensible to a future network
    # with multiple outputs.
    for output_index in range(
        quantized_weights.shape[0]
    ):

        # Iterate over every hidden-neuron input connected to the output.
        for hidden_index in range(
            quantized_weights.shape[1]
        ):
            rows.append(
                create_parameter_row(
                    parameter_type="weight",
                    layer="output",
                    row=output_index,
                    column=hidden_index,
                    value=quantized_weights[
                        output_index,
                        hidden_index,
                    ],
                )
            )


# =============================================================================
# Output-layer bias export
# =============================================================================

def export_output_bias(
    rows,
    output_bias,
):
    """Quantize and append output-layer biases to the CSV records."""

    # The current network contains one output neuron and therefore one output
    # bias.
    #
    # The output calculation is:
    #
    #                         7
    #                         ---
    #                         \
    #     predicted_return =   > h[i] * W[i] + b
    #                         /
    #                         ---
    #                         i=0
    quantized_bias = quantize_array(
        output_bias
    )

    # Keep the loop generic so the same CSV organization can support more than
    # one output neuron in a future architecture.
    for output_index in range(
        quantized_bias.shape[0]
    ):
        rows.append(
            create_parameter_row(
                parameter_type="bias",
                layer="output",
                row=output_index,
                column=0,
                value=quantized_bias[
                    output_index
                ],
            )
        )


# =============================================================================
# Complete parameter conversion
# =============================================================================

def create_quantized_rows(parameters):
    """Convert all trained parameters into hardware-oriented CSV records."""

    # Create the list that will contain every CSV parameter record.
    rows = []

    # Extract the arrays stored by python/train.py.
    hidden_weights = parameters[
        "hidden_weights"
    ]

    hidden_bias = parameters[
        "hidden_bias"
    ]

    output_weights = parameters[
        "output_weights"
    ]

    output_bias = parameters[
        "output_bias"
    ]

    # Export the first Dense layer.
    #
    # This generates:
    #
    #     8 x 8 = 64 hidden weights
    #
    # followed by:
    #
    #     8 hidden biases
    export_hidden_weights(
        rows,
        hidden_weights,
    )

    export_hidden_bias(
        rows,
        hidden_bias,
    )

    # Export the output Dense layer.
    #
    # This generates:
    #
    #     1 x 8 = 8 output weights
    #
    # followed by:
    #
    #     1 output bias
    export_output_weights(
        rows,
        output_weights,
    )

    export_output_bias(
        rows,
        output_bias,
    )

    # The current network therefore produces:
    #
    #     64 hidden weights
    #      8 hidden biases
    #      8 output weights
    #      1 output bias
    #     -----------------
    #     81 parameters
    #
    # This matches the number of trainable parameters reported by Keras.
    return rows


# =============================================================================
# CSV storage
# =============================================================================

def save_quantized_parameters(rows):
    """Save the quantized parameters using the hardware-facing CSV format."""

    # Ensure that the destination directory exists.
    #
    # Normally python/train.py already creates build/parameters/, but this
    # keeps export_weights.py usable as an independent processing stage.
    QUANTIZED_PARAMETER_FILE.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Define the CSV column order explicitly.
    #
    # Keeping the schema stable is important because the CSV becomes an
    # interface between several independent components:
    #
    #     Python exporter
    #     Python fixed-point reference model
    #     simulation utilities
    #     VHDL parameter generator
    #
    # The expected CSV header is:
    #
    # type,layer,row,column,value,width,fraction_bits
    fieldnames = [
        "type",
        "layer",
        "row",
        "column",
        "value",
        "width",
        "fraction_bits",
    ]

    # Open the destination file for writing.
    #
    # newline="" prevents Python's CSV module from introducing additional
    # blank lines on platforms where newline translation is performed.
    with open(
        QUANTIZED_PARAMETER_FILE,
        "w",
        newline="",
        encoding="utf-8",
    ) as csv_file:

        # Create the CSV writer.
        writer = csv.DictWriter(
            csv_file,
            fieldnames=fieldnames,
        )

        # Write:
        #
        # type,layer,row,column,value,width,fraction_bits
        writer.writeheader()

        # Write all quantized neural-network parameters.
        writer.writerows(
            rows
        )

    print(
        f"Exported {len(rows)} parameters"
    )

    print(
        "Saved quantized parameters to:"
    )

    print(
        QUANTIZED_PARAMETER_FILE
    )


# =============================================================================
# Main parameter-export flow
# =============================================================================

def main():
    """Execute the floating-point to fixed-point parameter export flow."""

    # The complete flow implemented by this script is:
    #
    # python/train.py
    #       |
    #       v
    # build/parameters/weights_float.npz
    #       |
    #       v
    # load_parameters()
    #       |
    #       +--> hidden_weights
    #       +--> hidden_bias
    #       +--> output_weights
    #       +--> output_bias
    #       |
    #       v
    # create_quantized_rows()
    #       |
    #       +--> transpose weights
    #       |
    #       +--> quantize hidden weights
    #       |
    #       +--> quantize hidden biases
    #       |
    #       +--> quantize output weights
    #       |
    #       +--> quantize output bias
    #       |
    #       v
    # hardware-oriented parameter records
    #       |
    #       v
    # save_quantized_parameters()
    #       |
    #       v
    # build/parameters/weights_q.csv
    #       |
    #       +------------------------+
    #       |                        |
    #       v                        v
    # reference_model.py        FPGA parameter
    #                           generation flow

    # Load the trained floating-point parameters.
    parameters = load_parameters()

    # Convert all parameters to the configured fixed-point representation and
    # reorganize Dense-layer matrices into a hardware-oriented indexing order.
    rows = create_quantized_rows(
        parameters
    )

    # Store the quantized parameter records.
    save_quantized_parameters(
        rows
    )


