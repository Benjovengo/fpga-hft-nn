# =============================================================================
# Why transpose the Dense-layer matrices?
# =============================================================================

# Keras organizes a Dense-layer matrix according to the software operation:
#
#     output = input @ kernel + bias
#
# Therefore, the kernel is stored as:
#
#     kernel[input][neuron]
#
# A hardware neuron, however, naturally requires:
#
#     neuron 0:
#         weight for input 0
#         weight for input 1
#         ...
#         weight for input 7
#
#     neuron 1:
#         weight for input 0
#         weight for input 1
#         ...
#         weight for input 7
#
# The hardware-oriented representation is therefore:
#
#     weight[neuron][input]
#
# which is the transpose of the Keras representation.
#
# For the hidden layer:
#
# Keras:
#
#     hidden_weights[input][neuron]
#
# becomes:
#
# FPGA:
#
#     hidden_weights[neuron][input]
#
# This makes the CSV ordering directly correspond to the weights consumed by
# each future VHDL neuron.


# =============================================================================
# CSV as the software/hardware parameter contract
# =============================================================================

# The CSV deliberately contains more information than only the integer value.
#
# Example:
#
#     type,layer,row,column,value,width,fraction_bits
#     weight,hidden,0,0,314,16,12
#
# This record identifies:
#
#     what the parameter is:
#
#         weight
#
#     where it belongs:
#
#         hidden layer
#
#     which neuron owns it:
#
#         row 0
#
#     which input it multiplies:
#
#         column 0
#
#     its signed integer representation:
#
#         314
#
#     its hardware storage width:
#
#         16 bits
#
#     its implied fractional precision:
#
#         12 bits
#
# Therefore, the CSV is self-describing enough for another script to convert
# the parameters into a synthesizable VHDL package or Intel memory
# initialization file.


# =============================================================================
# Important synthesis distinction
# =============================================================================

# The CSV is useful for software processing and simulation, but the final
# synthesized FPGA should not depend on opening this host-side CSV file at
# runtime.
#
# A later build-time conversion stage should transform:
#
#     weights_q.csv
#
# into a synthesizable representation such as:
#
#     VHDL constant arrays
#
# or:
#
#     Intel .mif memory initialization
#
# For example:
#
# weights_q.csv
#       |
#       +-------------------------------+
#       |                               |
#       v                               v
# simulation                     FPGA build
#       |                               |
#       v                               v
# VHDL TextIO                Python converter
#                                       |
#                               +-------+-------+
#                               |               |
#                               v               v
#                          VHDL package       .mif
#                               |               |
#                               +-------+-------+
#                                       |
#                                       v
#                                   Quartus
#
# This keeps weights_q.csv as the single software-generated source of truth
# while still producing synthesizable FPGA artifacts.
