import csv
import sys
from pathlib import Path


# =============================================================================
# Project path configuration
# =============================================================================

# Determine the project root.
PROJECT_ROOT = Path(__file__).resolve().parents[1]


# Add the project root to the Python module search path.
sys.path.insert(
    0,
    str(PROJECT_ROOT),
)


# =============================================================================
# Project configuration
# =============================================================================

# INPUT_FEATURES
#     Defines the number and order of NN input features.
#
# TEST_VECTOR_FILE
#     Output CSV consumed later by the VHDL/Verilog testbench.
#
# VECTOR_DIR
#     Directory containing generated verification vectors.
from config.model_config import (
    INPUT_FEATURES,
    TEST_VECTOR_FILE,
    VECTOR_DIR,
)


# =============================================================================
# Dataset imports
# =============================================================================

# Load the processed features and perform the same chronological split used by
# training.
from python.dataset import (
    extract_arrays,
    load_processed_data,
    split_dataset,
)


# =============================================================================
# Fixed-point reference-model imports
# =============================================================================

# infer_fixed()
#     Executes one complete integer NN inference.
#
# load_parameters()
#     Loads weights_q.csv.
#
# quantize_input()
#     Converts a floating-point input vector into the hardware fixed-point
#     representation.
from python.reference_model import (
    infer_fixed,
    load_parameters,
    quantize_input,
)


# =============================================================================
# Test-vector configuration
# =============================================================================

# Number of independent test vectors exported for RTL simulation.
#
# Keeping this relatively small makes simulation fast while still providing
# enough vectors to verify multiple numerical cases.
NUMBER_VECTORS = 100


# =============================================================================
# Main test-vector generation
# =============================================================================

def main():
    """Generate fixed-point NN input/output vectors for RTL verification."""

    # Create build/vectors/ if it does not already exist.
    VECTOR_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    # -------------------------------------------------------------------------
    # Load the processed dataset
    # -------------------------------------------------------------------------

    # The dataset was previously generated by:
    #
    #     python/features.py
    dataframe = load_processed_data()


    # -------------------------------------------------------------------------
    # Extract numerical input and target arrays
    # -------------------------------------------------------------------------

    # x contains the eight configured NN input features.
    #
    # y contains target_return.
    #
    # y is not directly required for FPGA equivalence testing because the RTL
    # is compared against the fixed-point Python output rather than against the
    # original market target.
    x, y = extract_arrays(
        dataframe
    )


    # -------------------------------------------------------------------------
    # Reproduce the chronological dataset split
    # -------------------------------------------------------------------------

    # Use the test partition only.
    #
    # This ensures that FPGA verification vectors come from samples that were
    # not used to update the neural-network weights during training.
    (
        _,
        _,
        _,
        _,
        x_test,
        _,
    ) = split_dataset(
        x,
        y,
    )


    # -------------------------------------------------------------------------
    # Load quantized NN parameters
    # -------------------------------------------------------------------------

    (
        hidden_weights,
        hidden_bias,
        output_weights,
        output_bias,
    ) = load_parameters()


    # -------------------------------------------------------------------------
    # Create CSV columns
    # -------------------------------------------------------------------------

    # Generate:
    #
    #     x0
    #     x1
    #     ...
    #     x7
    #
    # dynamically from INPUT_FEATURES.
    input_columns = [
        f"x{index}"
        for index
        in range(
            len(INPUT_FEATURES)
        )
    ]

    # Add the expected fixed-point NN output.
    fieldnames = [
        *input_columns,
        "expected",
    ]


    # -------------------------------------------------------------------------
    # Open output CSV
    # -------------------------------------------------------------------------

    with open(
        TEST_VECTOR_FILE,
        "w",
        newline="",
        encoding="utf-8",
    ) as csv_file:

        writer = csv.DictWriter(
            csv_file,
            fieldnames=fieldnames,
        )

        # Write:
        #
        # x0,x1,x2,x3,x4,x5,x6,x7,expected
        writer.writeheader()


        # ---------------------------------------------------------------------
        # Generate vectors
        # ---------------------------------------------------------------------

        # Limit the number of vectors to NUMBER_VECTORS.
        for sample in x_test[
            :NUMBER_VECTORS
        ]:

            # Convert the floating-point feature vector into fixed-point integer
            # values.
            quantized_input = (
                quantize_input(
                    sample
                )
            )

            # Execute the exact integer inference algorithm that the VHDL is
            # expected to reproduce.
            expected = infer_fixed(
                quantized_input,
                hidden_weights,
                hidden_bias,
                output_weights,
                output_bias,
            )

            # Create the CSV record containing all quantized NN inputs.
            row = {
                f"x{index}": int(
                    quantized_input[
                        index
                    ]
                )
                for index
                in range(
                    len(
                        INPUT_FEATURES
                    )
                )
            }

            # Append the expected fixed-point output.
            row[
                "expected"
            ] = expected

            # Store the complete vector.
            writer.writerow(
                row
            )


    # -------------------------------------------------------------------------
    # Report generated artifact
    # -------------------------------------------------------------------------

    print(
        f"Generated {TEST_VECTOR_FILE}"
    )


# =============================================================================
# Script entry point
# =============================================================================

# Execute when running:
#
#     python -m python.generate_vectors
if __name__ == "__main__":
    main()
    