library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- =============================================================================
-- Neural-network fixed-point types and helper functions.
--
-- This package defines the numerical contract shared by the neural-network RTL.
-- The current model is 8 inputs -> Dense(8) -> ReLU -> Dense(1).
-- Values use signed 16-bit fixed-point storage with 12 fractional bits.
-- Wider intermediate accumulators are used to avoid overflow during MACs.
-- =============================================================================
package nn_types_pkg is

    -- Number of input features generated by the market-data feature engine.
    constant C_INPUT_SIZE : positive := 8;

    -- Number of neurons in the hidden Dense layer.
    constant C_HIDDEN_SIZE : positive := 8;

    -- Number of bits used by stored inputs, weights, biases, and final outputs.
    constant C_DATA_WIDTH : positive := 16;

    -- Number of fractional bits in the signed fixed-point representation.
    constant C_FRACTION_BITS : natural := 12;

    -- Width used by multiply-accumulate datapaths.
    -- 40 bits provides headroom above a 32-bit 16x16 product while summing
    -- eight products and an aligned bias.
    constant C_ACC_WIDTH : positive := 40;

    -- Width of the free-running cycle timestamp used for latency measurement.
    constant C_TIMESTAMP_WIDTH : positive := 32;

    -- Signed fixed-point sample type.
    subtype t_data is signed(C_DATA_WIDTH - 1 downto 0);

    -- Signed accumulator type used during Dense-layer MAC calculations.
    subtype t_acc is signed(C_ACC_WIDTH - 1 downto 0);

    -- Array used for input vectors and hidden-layer vectors.
    type t_data_array is array (natural range <>) of t_data;

    -- Two-dimensional matrix used for Dense-layer weights.
    -- The RTL convention is weight(neuron, input).
    type t_weight_matrix is array (natural range <>, natural range <>) of t_data;

    -- Saturate a wide signed value to the configured t_data width.
    function saturate_to_data(value : t_acc) return t_data;

    -- Apply integer/fixed-point ReLU and return a saturated t_data value.
    function relu_to_data(value : t_acc) return t_data;

end package;

package body nn_types_pkg is

    function saturate_to_data(value : t_acc) return t_data is
        -- Maximum signed 16-bit value: 0x7FFF for C_DATA_WIDTH = 16.
        constant C_MAX_DATA : t_data :=
            to_signed((2 ** (C_DATA_WIDTH - 1)) - 1, C_DATA_WIDTH);

        -- Minimum signed 16-bit value: 0x8000 for C_DATA_WIDTH = 16.
        constant C_MIN_DATA : t_data :=
            to_signed(-(2 ** (C_DATA_WIDTH - 1)), C_DATA_WIDTH);

        -- Accumulator-width versions are used for safe comparisons.
        constant C_MAX_ACC : t_acc := resize(C_MAX_DATA, C_ACC_WIDTH);
        constant C_MIN_ACC : t_acc := resize(C_MIN_DATA, C_ACC_WIDTH);
    begin
        -- Clamp values above the positive representable limit.
        if value > C_MAX_ACC then
            return C_MAX_DATA;

        -- Clamp values below the negative representable limit.
        elsif value < C_MIN_ACC then
            return C_MIN_DATA;

        -- Otherwise the value fits and can be resized directly.
        else
            return resize(value, C_DATA_WIDTH);
        end if;
    end function;

    function relu_to_data(value : t_acc) return t_data is
        constant C_ZERO : t_data := (others => '0');
    begin
        -- ReLU suppresses all negative values.
        if value < 0 then
            return C_ZERO;

        -- Positive values still pass through the same output saturation rule.
        else
            return saturate_to_data(value);
        end if;
    end function;

end package body;
